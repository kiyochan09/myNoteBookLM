def correct_japanese_text(text: str) -> str:
    """
    日本語OCR認識テキストに対してカタカナ誤認識・濁点半濁点混同・記号ノイズを自動修復する。
    """
    if not text:
        return ""

    s = text

    # 1. 辞書置換（長い用語から優先置換）
    for raw_k, canonical_v in sorted(CANONICAL_TERMS_MAP.items(), key=lambda x: len(x[0]), reverse=True):
        if raw_k in s:
            s = s.replace(raw_k, canonical_v)

    # 2. 正規表現置換ルール
    for pattern, repl in REGEX_REPLACEMENTS:
        s = pattern.sub(repl, s)

    # 3. 辞書再適用 (正規表現で中間修復されたトークンを最終正規化)
    for raw_k, canonical_v in sorted(CANONICAL_TERMS_MAP.items(), key=lambda x: len(x[0]), reverse=True):
        if raw_k in s:
            s = s.replace(raw_k, canonical_v)

    return s


def correct_ocr_lines(lines: List[Dict[str, Any]], doc_type: str = "japanese") -> List[Dict[str, Any]]:
    """
    OCR認識行リスト（各行の辞書）に対してテキスト修復を一括適用する。
    """
    if not lines or doc_type == "western":
        return lines

    for l in lines:
        t = l.get("text", "")
        if t:
            l["text"] = correct_japanese_text(t)

    return lines


def extract_proofread_candidates(
    text: str,
    context_window: int = 30,
    engine: str = "hybrid"
) -> List[Dict[str, Any]]:
    """
    テキスト内の校正候補（修正前、修正後、理由、文字位置、前後文脈スニペット）を抽出する。
    
    Parameters:
        text: 対象テキスト
        context_window: 前後文脈の文字数 (デフォルト30文字)
        engine: 'rule' (ルールのみ), 'kwja' (KWJAのみ), 'hybrid' (ルール+KWJA)
    """
    if not text or not text.strip():
        return []

    candidates: List[Dict[str, Any]] = []

    # 1. ルール・辞書ベースの抽出
    if engine in ("rule", "hybrid"):
        # 1-1. 辞書置換候補の走査
        for raw_k, canonical_v in sorted(CANONICAL_TERMS_MAP.items(), key=lambda x: len(x[0]), reverse=True):
            if raw_k == canonical_v:
                continue
            start = 0
            while True:
                idx = text.find(raw_k, start)
                if idx == -1:
                    break
                end_idx = idx + len(raw_k)
                cb_start = max(0, idx - context_window)
                cb = text[cb_start:idx]
                ca_end = min(len(text), end_idx + context_window)
                ca = text[end_idx:ca_end]

                candidates.append({
                    "id": f"cand_rule_{idx}_{end_idx}",
                    "original": raw_k,
                    "suggested": canonical_v,
                    "reason": "カタカナ固有名詞・専門用語正規化",
                    "engine": "rule",
                    "start_idx": idx,
                    "end_idx": end_idx,
                    "context_before": cb,
                    "context_after": ca,
                    "status": "pending"
                })
                start = end_idx

        # 1-2. 正規表現置換ルールの走査
        for pattern, repl in REGEX_REPLACEMENTS:
            for m in pattern.finditer(text):
                matched_raw = m.group(0)
                try:
                    sugg = pattern.sub(repl, matched_raw)
                except Exception:
                    sugg = matched_raw
                if sugg != matched_raw:
                    start_idx = m.start()
                    end_idx = m.end()
                    cb_start = max(0, start_idx - context_window)
                    cb = text[cb_start:start_idx]
                    ca_end = min(len(text), end_idx + context_window)
                    ca = text[end_idx:ca_end]

                    candidates.append({
                        "id": f"cand_regex_{start_idx}_{end_idx}",
                        "original": matched_raw,
                        "suggested": sugg,
                        "reason": "OCR記号ノイズ・長音促音補正",
                        "engine": "rule",
                        "start_idx": start_idx,
                        "end_idx": end_idx,
                        "context_before": cb,
                        "context_after": ca,
                        "status": "pending"
                    })

    # 2. KWJA ベースの抽出
    if engine in ("kwja", "hybrid"):
        try:
            from app.ocr_pipeline.kwja_corrector import extract_kwja_candidates, is_kwja_available
            if is_kwja_available():
                kwja_cands = extract_kwja_candidates(text, context_window=context_window)
                candidates.extend(kwja_cands)
        except Exception:
            pass

    # 重複スパンの統合と位置順ソート
    candidates.sort(key=lambda x: x["start_idx"])

    unique_candidates: List[Dict[str, Any]] = []
    seen_spans = set()
    for c in candidates:
        span_key = (c["start_idx"], c["end_idx"])
        if span_key not in seen_spans:
            seen_spans.add(span_key)
            unique_candidates.append(c)

    return unique_candidates

