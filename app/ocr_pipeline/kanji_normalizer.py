# 2. CJK互換漢字（U+F900〜U+FAFF）から新字体へのマッピング（NFKCで標準化されるもの）
COMPAT_KANJI_MAP: Dict[str, str] = {}
for code in range(0xF900, 0xFAFF + 1):
    ch = chr(code)
    decomp = unicodedata.normalize('NFKC', ch)
    if decomp != ch and len(decomp) == 1:
        final_ch = KANJI_KYUJITAI_TO_SHINJITAI.get(decomp, decomp)
        COMPAT_KANJI_MAP[ch] = final_ch

# 統合変換辞書
ALL_KYUJITAI_MAP: Dict[str, str] = {**KANJI_KYUJITAI_TO_SHINJITAI, **COMPAT_KANJI_MAP}

# 高速変換用 str.maketrans
KYUJITAI_TRANSLATION_TABLE = str.maketrans(ALL_KYUJITAI_MAP)

def normalize_kyujitai(text: str) -> str:
    """
    旧字体・異体字・CJK互換漢字を新字体（常用漢字）に正規化する。
    例: 戰 -> 戦, 體 -> 体, 國 -> 国, 靑 -> 青, 者 -> 者, 海 -> 海, 說 -> 説, 變 -> 変
    """
    if not text:
        return text
    return text.translate(KYUJITAI_TRANSLATION_TABLE)
